def df(rows=ROWS):
    return pd.DataFrame(rows, columns=["date", "open", "high", "low", "close", "volume"])


def run(d, **params):
    return screen_xianren({"2492": d}, {"2492": "華新科"}, params=params or None)


def test_hua_xin_ke_second_volume_day():
    r = run(df())
    assert len(r) == 1
    x = r[0]
    assert x["probe_date"] == "20261005" and x["probe_high"] == 396 and x["probe_low"] == 365
    assert x["stop"] == 365 and x["pause_days"] == 1
    assert x["probe_vol_ratio"] >= 3 and 1.5 <= x["today_vol_ratio"] < 2
    assert x["broke_top"] is True and x["box_high"] < 396


def test_not_on_probe_day_or_pause_day():
    assert run(df(ROWS[:-2])) == []        # 10/05 當天：仙人指路本身不抓
    assert run(df(ROWS[:-1])) == []        # 10/06：中間還沒盤整（至少 1 天）


def test_today_volume_too_small():
    rows = ROWS[:-1] + [("20261007", 389, 428, 388, 427.5, 30000)]   # 30,000 張 ≈ 均量 1 倍
    assert run(df(rows)) == []


def test_pause_close_breaks_probe_low():
    rows = ROWS[:-2] + [("20261006", 370, 372, 355, 360, 40000), ROWS[-1]]   # 盤整收盤 360 < 365
    assert run(df(rows)) == []


def test_pause_already_above_shadow_top():
    rows = ROWS[:-2] + [("20261006", 370, 400, 362.5, 389.5, 40000), ROWS[-1]]   # 盤整中已衝過 396
    assert run(df(rows)) == []


def test_must_close_above_probe_body():
    base = ROWS[:-2] + [("20261006", 370, 372, 366, 368, 30000)]
    assert run(df(base + [("20261007", 369, 377, 368, 376, 51687)])) == []      # 收 376 < 實體上緣 377.5
    assert len(run(df(base + [("20261007", 369, 380, 368, 378, 51687)]))) == 1  # 收 378 站上


def test_only_first_attack():
    # 10/07 出量收紅攻一次（沒過頂）→ 10/08 再出量是第三次，不重抓
    rows = ROWS[:-1] + [("20261007", 390, 394, 388, 393, 50000), ("20261008", 393, 395, 390, 394.5, 52000)]
    first = run(df(rows[:-1]))
    assert len(first) == 1 and first[0]["pause_days"] == 1
    assert run(df(rows)) == []


def test_short_shadow_is_not_probe():
    rows = ROWS[:-3] + [("20261005", 377.5, 380, 365, 378, 94143)] + ROWS[-2:]   # 沒有上影線
    assert run(df(rows)) == []


